#!/usr/bin/env python3
"""Compiles shaders/*.vert|*.frag (FXAA) to SPIR-V and writes src/hle/nvn/postfx_spv.h.

Needs glslangValidator and spirv-val (Ubuntu: apt install glslang-tools spirv-tools). The header is checked in, so
building the app needs neither: run this only after editing a shader.
"""
import os, struct, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADERS = [  # (array name, source, stage, defines)
    ("kFullscreenVert", "fullscreen.vert", "vert", []),
    ("kFxaaQualityFrag", "fxaa.frag", "frag", ["FXAA_STEPS=12"]),
    ("kFxaaFastFrag", "fxaa.frag", "frag", ["FXAA_STEPS=6"]),
]

def compile_one(src, stage, defines, out):
    cmd = ["glslangValidator", "-V", "--target-env", "vulkan1.1", "-S", stage,
           "-I" + os.path.join(ROOT, "shaders")]
    cmd += ["-D" + d for d in defines]
    cmd += [os.path.join(ROOT, "shaders", src), "-o", out]
    subprocess.check_call(cmd, stdout=subprocess.DEVNULL)
    subprocess.check_call(["spirv-val", "--target-env", "vulkan1.1", out])

def main():
    lines = [
        "// GENERATED by tools/gen_postfx_shaders.py from shaders/*: do not edit by hand.",
        "// SPIR-V (Vulkan 1.1, capabilities Shader and ImageQuery only) of the post-processing passes",
        "// (FXAA 3.11, ported from gu-native).",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace dsr::hle::nvn::postfx_spv {",
        "",
    ]
    with tempfile.TemporaryDirectory() as tmp:
        for name, src, stage, defines in SHADERS:
            out = os.path.join(tmp, name + ".spv")
            compile_one(src, stage, defines, out)
            data = open(out, "rb").read()
            words = struct.unpack("<%dI" % (len(data) // 4), data)
            lines.append("// %s%s" % (src, (" (" + " ".join(defines) + ")") if defines else ""))
            lines.append("inline constexpr uint32_t %s[] = {" % name)
            for i in range(0, len(words), 8):
                lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
            lines.append("};")
            lines.append("inline constexpr size_t %sSize = sizeof(%s);" % (name, name))
            lines.append("")
    lines.append("}  // namespace dsr::hle::nvn::postfx_spv")
    path = os.path.join(ROOT, "src", "hle", "nvn", "postfx_spv.h")
    open(path, "w", newline="\n").write("\n".join(lines) + "\n")
    print("wrote", path)

if __name__ == "__main__":
    sys.exit(main())
